import type { Metadata, Viewport } from 'next';
import type { ReactNode } from 'react';
import './globals.css';
import { Providers } from './providers';

export const metadata: Metadata = {
  title: { default: 'Creator OS', template: '%s · Creator OS' },
  description: 'Private creative production, publishing and collaboration command centre.',
  manifest: '/manifest.webmanifest',
  appleWebApp: { capable: true, title: 'Creator OS', statusBarStyle: 'black-translucent' },
  icons: { icon: '/pwa-icon/192', apple: '/pwa-icon/192' },
  robots: { index: false, follow: false },
};

export const viewport: Viewport = {
  width: 'device-width',
  initialScale: 1,
  viewportFit: 'cover',
  themeColor: [
    { media: '(prefers-color-scheme: light)', color: '#f6f7fb' },
    { media: '(prefers-color-scheme: dark)', color: '#0d0f17' },
  ],
};

// Applied before first paint so the theme never flashes.
const themeScript = `try{var t=localStorage.getItem('cos-theme');if(!t){t=matchMedia('(prefers-color-scheme: dark)').matches?'dark':'light'}document.documentElement.dataset.theme=t}catch(e){}`;

export default function RootLayout({ children }: { children: ReactNode }) {
  return (
    <html lang="en" suppressHydrationWarning>
      <head>
        <script dangerouslySetInnerHTML={{ __html: themeScript }} />
      </head>
      <body className="min-h-dvh antialiased">
        <Providers>{children}</Providers>
      </body>
    </html>
  );
}
